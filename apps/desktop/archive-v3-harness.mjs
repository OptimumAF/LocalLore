const executions = [];
async function run(name, command, args, env, timeoutMs) {
    const result = await new Promise((resolve, reject) => {
        let stdout = "", stderr = "", overflow = false, timedOut = false;
        const child = spawn(command, args, { cwd: root, windowsHide: true, shell: false, stdio: ["ignore", "pipe", "pipe"],
            env: { ...process.env, CARGO_PROFILE_DEV_DEBUG: "0", CARGO_PROFILE_TEST_DEBUG: "0", CARGO_INCREMENTAL: "0", CARGO_BUILD_JOBS: "1", ...env } });
        const keep = (which, chunk) => {
            const text = chunk.toString();
            if (which === "stdout") stdout += text; else stderr += text;
            if (Buffer.byteLength(stdout) + Buffer.byteLength(stderr) > 2 * 1024 * 1024) {
                overflow = true; stdout = stdout.slice(0, 512 * 1024); stderr = stderr.slice(0, 512 * 1024); child.kill();
            }
        };
        child.stdout.on("data", (chunk) => keep("stdout", chunk));
        child.stderr.on("data", (chunk) => keep("stderr", chunk));
        const timer = setTimeout(() => { timedOut = true; child.kill(); }, timeoutMs);
        child.once("error", (error) => { clearTimeout(timer); reject(error); });
        child.once("close", (code, signal) => { clearTimeout(timer); resolve({ code, signal, timedOut, overflow, stdout, stderr }); });
    });
    await writeFile(path.join(folder, `${name}.stdout.log`), result.stdout, { flag: "wx" });
    await writeFile(path.join(folder, `${name}.stderr.log`), result.stderr, { flag: "wx" });
    executions.push({ name, command: name.startsWith("app-") ? "<owned-app>" : command, args, code: result.code,
        signal: result.signal, timedOut: result.timedOut, overflow: result.overflow,
        stdoutSHA256: hash(result.stdout), stderrSHA256: hash(result.stderr) });
    await writeFile(path.join(folder, "executions.json"), JSON.stringify(executions, null, 2));
    assert(!result.overflow && !result.timedOut && result.code === 0, `Owned child failed: ${name}; inspect retained bounded logs`);
}
