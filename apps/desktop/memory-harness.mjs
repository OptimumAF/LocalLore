let runNumber = 0;
async function run(command, args, env = {}) {
    await checkInspectionHashes();
    const logName = `run-${++runNumber}`;
    const bounded = { stdout: Buffer.alloc(0), stderr: Buffer.alloc(0) };
    let truncated = false;
    let timedOut = false;
    const started = new Date().toISOString();
    const inherited = { ...process.env };
    if (inspecting) {
        for (const key of Object.keys(inherited))
            if (
                key.startsWith("LOCALLORE_") &&
                /HARNESS|TEST_|ARTIFACT_DIR/.test(key)
            )
                delete inherited[key];
    }
    await new Promise((resolve, reject) => {
        const child = spawn(command, args, {
            cwd: root,
            stdio: ["ignore", "pipe", "pipe"],
            windowsHide: true,
            shell: false,
            env: { ...inherited, ...env },
        });
        for (const channel of ["stdout", "stderr"])
            child[channel].on("data", (chunk) => {
                const available = 262144 - bounded[channel].length;
                if (chunk.length > available) truncated = true;
                if (available > 0)
                    bounded[channel] = Buffer.concat([
                        bounded[channel],
                        chunk.subarray(0, available),
                    ]);
            });
        const timer = setTimeout(
            () => {
                timedOut = true;
                child.kill();
            },
            command === "cargo" ? 900000 : 240000,
        );
        child.once("error", (error) => {
            clearTimeout(timer);
            // close follows spawn errors; preserve its bounded outcome there.
            bounded.stderr = Buffer.from(String(error.message).slice(0, 1000));
        });
        child.once("close", async (code, signal) => {
            try {
                clearTimeout(timer);
                for (const channel of ["stdout", "stderr"])
                    await writeFile(
                        path.join(folder, `${logName}-${channel}.log`),
                        bounded[channel],
                    );
                await writeFile(
                    path.join(folder, `${logName}-process.json`),
                    JSON.stringify(
                        {
                            command:
                                command === executable
                                    ? "owned-native-app"
                                    : command,
                            args,
                            code,
                            signal,
                            truncated,
                            timedOut,
                            started,
                            ended: new Date().toISOString(),
                            sourceRevision,
                        },
                        null,
                        2,
                    ),
                );
                console.log(`${logName}: exit ${code}, bounded logs retained`);
                await checkInspectionHashes();
                code === 0 && !timedOut && (!inspecting || !truncated)
                    ? resolve()
                    : reject(
                          new Error(
                              timedOut
                                  ? "ChildDeadline"
                                  : truncated && inspecting
                                    ? "ChildOutputOverflow"
                                    : `ChildExit${code}`,
                          ),
                      );
            } catch (error) {
                reject(error);
            }
        });
    });
}
