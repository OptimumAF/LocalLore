class AuthKeyGuard:
    """A metadata-only native key lease. FILE_SHARE_READ denies write/delete."""
    def __init__(self):
        self.kernel=None;self.key=None;self.handles=set();self.failed_close=False;self.descriptor=None

    def _plain(self,path,directory=False):
        for part in (path,*path.parents):
            info=part.lstat()
            _need(not getattr(info,"st_file_attributes",0)&0x400 and not part.is_symlink(),"auth")
            _need(part.is_dir() if part!=path or directory else part.is_file(),"auth")
        _need(path.resolve(strict=True)==path,"auth")

    def _open_read(self,path):
        handle=self.kernel.CreateFileW(str(path),0x80000000,1,None,3,0x00200000,None)
        _need(handle not in (None,0,ctypes.c_void_p(-1).value),"auth")
        self.handles.add(handle)
        return handle

    def _metadata(self,handle):
        value=_FileInformation()
        _need(self.kernel.GetFileInformationByHandle(handle,ctypes.byref(value)),"auth")
        metadata=dict(volume_serial=int(value.volume),file_index=(int(value.index_high)<<32)|int(value.index_low),
            bytes=(int(value.size_high)<<32)|int(value.size_low),attributes=int(value.attributes),
            creation_filetime=(int(value.creation.dwHighDateTime)<<32)|int(value.creation.dwLowDateTime),
            write_filetime=(int(value.write.dwHighDateTime)<<32)|int(value.write.dwLowDateTime),links=int(value.links))
        _need(metadata["bytes"]>0 and metadata["links"]>=1 and not metadata["attributes"]&(0x10|0x400),"auth")
        return metadata

    def _close(self,handle):
        try:
            ok=bool(self.kernel.CloseHandle(handle))
        except (OSError,ValueError):
            ok=False
        if ok:self.handles.discard(handle)
        else:self.failed_close=True
        return ok

    def open(self,expected):
        _need(self.kernel is None and os.name=="nt","auth")
        _need(ctypes.sizeof(_FileInformation)==52 and
            [getattr(_FileInformation,k).offset for k,_ in _FileInformation._fields_]==[0,4,12,20,28,32,36,40,44,48],"auth")
        kernel=ctypes.WinDLL("kernel32",use_last_error=True)
        kernel.CreateFileW.argtypes=[wintypes.LPCWSTR,wintypes.DWORD,wintypes.DWORD,ctypes.c_void_p,wintypes.DWORD,wintypes.DWORD,wintypes.HANDLE]
        kernel.CreateFileW.restype=wintypes.HANDLE
        kernel.GetFileInformationByHandle.argtypes=[wintypes.HANDLE,ctypes.POINTER(_FileInformation)]
        kernel.GetFileInformationByHandle.restype=wintypes.BOOL
        kernel.CloseHandle.argtypes=[wintypes.HANDLE];kernel.CloseHandle.restype=wintypes.BOOL
        self.kernel=kernel
        shell=ctypes.WinDLL("shell32",use_last_error=True)
        shell.SHGetFolderPathW.argtypes=[wintypes.HWND,ctypes.c_int,wintypes.HANDLE,wintypes.DWORD,wintypes.LPWSTR]
        shell.SHGetFolderPathW.restype=ctypes.c_long
        text=ctypes.create_unicode_buffer(32768)
        _need(shell.SHGetFolderPathW(None,0x28,None,0,text)==0,"auth")
        profile=Path(text.value);key=profile/".android/adbkey"
        _need(key.is_absolute() and str(key)==expected,"auth")
        self._plain(key.parent,directory=True);self._plain(key)
        self.key=self._open_read(key)
        self.descriptor=dict(path=str(key),native_profile=str(profile),metadata=self._metadata(self.key))
        return self.check()

    def check(self):
        _need(self.key is not None and not self.failed_close,"auth")
        path=Path(self.descriptor["path"]);self._plain(path)
        _need(_same(self._metadata(self.key),self.descriptor["metadata"]),"auth")
        fresh=None
        try:
            fresh=self._open_read(path)
            _need(_same(self._metadata(fresh),self.descriptor["metadata"]),"auth")
        finally:
            if fresh is not None:_need(self._close(fresh),"cleanup")
        return copy.deepcopy(self.descriptor)

    def close(self):
        if self.kernel is not None:
            for handle in list(self.handles):self._close(handle)
        return not self.handles and not self.failed_close


def _observe(api,endpoint=None):
    native._check_abi();rows=[];tables=[]
    for family in (2,23):
        table=api.capture(family)
        decoded=decode_table(table.raw,family)
        stride=24 if family==2 else 56
        tables.append(dict(family=family,table_class=5,allocated_bytes=table.allocated_bytes,
            returned_bytes=len(table.raw),count=len(decoded),raw_sha256=hashlib.sha256(table.raw).hexdigest(),abi_checked=True))
        for ordinal,row in enumerate(decoded):
            selected=row.local_port==lease.PORT or endpoint is not None and family==2 and row.local_address=="127.0.0.1" \
                and row.local_port==endpoint["local_port"] and row.remote_address=="127.0.0.1" and row.remote_port==lease.PORT
            if selected:
                _need(len(rows)<64,"port")
                value=asdict(row);value.update(ordinal=ordinal,raw_hex=table.raw[4+ordinal*stride:4+(ordinal+1)*stride].hex())
                rows.append(value)
    return dict(version=1,port=lease.PORT,rows=rows,families=[2,23]),tables


