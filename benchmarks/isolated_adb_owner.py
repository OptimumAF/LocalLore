class ServerCapture:
    def __init__(self,root):
        root.mkdir();self.capture=env.LiveOutput(root);self.readers=[];self.pipes=[];self.failed=False;self.pipes_closed=False

    def start(self,child):
        self.pipes=[child.stdout,child.stderr]
        def drain(stream,channel):
            try:
                while True:
                    data=stream.read(4096)
                    if not data or not self.capture.append(channel,data):break
            except Exception:self.capture.failed.set()
        for channel,stream in enumerate(self.pipes):
            thread=threading.Thread(target=drain,args=(stream,channel),daemon=True)
            try:thread.start();self.readers.append(thread)
            except RuntimeError:
                self.failed=True;self.capture.failed.set();raise

    def guard(self):
        _need(not self.capture.failed.is_set() and not self.capture.overflow.is_set(),"capture")

    def close(self):
        for thread in self.readers:
            try:thread.join(timeout=2)
            except RuntimeError:self.failed=True
        stopped=not any(t.is_alive() for t in self.readers)
        if stopped:
            self.pipes_closed=True
            for stream in self.pipes:
                try:stream.close()
                except (OSError,ValueError):self.failed=True;self.pipes_closed=False
            try:self.capture.close()
            except (OSError,ValueError):self.failed=True
        self.failed=self.failed or not stopped or self.capture.failed.is_set() or self.capture.overflow.is_set()
        return stopped and not self.failed


class ProcessHandles:
    def __init__(self,api):
        self.api=api;self.handles={};self.failed_close=False

    def add(self,pid,expected=None):
        handle=self.api.open_process(pid)
        _need(handle not in self.handles,"identity")
        self.handles[handle]=None
        value=self.api.identity(handle)
        _need(self.api.alive(handle) and (expected is None or _same(value,expected)),"identity")
        self.handles[handle]=copy.deepcopy(value)
        return handle,copy.deepcopy(value)

    def guard(self):
        for handle,value in self.handles.items():
            _need(value is not None and self.api.alive(handle) and _same(self.api.identity(handle),value),"identity")

    def release(self,handle):
        try:closed=self.api.close_handle(handle) is True
        except (OSError,ValueError):closed=False
        if closed:self.handles.pop(handle,None)
        else:self.failed_close=True
        return closed

    def close(self):
        for handle in list(self.handles):self.release(handle)
        return not self.handles and not self.failed_close


