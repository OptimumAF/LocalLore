from dataclasses import dataclass
import io
import struct
import unittest
import zipfile

from scripts import audit_physical_model_apk as audit


OWNER = b"Lorg/locallore/app/DiagnosticsIntegrationTest;"
JUNIT = b"Lorg/junit/Test;"
OTHER_ANNOTATION = b"Lsynthetic/NotATest;"


def _uleb(value):
    assert 0 <= value <= 0xFFFFFFFF
    data = bytearray()
    while value >= 128:
        data.append((value & 127) | 128)
        value >>= 7
    data.append(value)
    return bytes(data)


@dataclass(frozen=True)
class _Method:
    name: bytes = b"reviewCase"
    flags: int = 1
    defined: bool = True
    has_code: bool = True
    declared_units: int = 1
    instructions: bytes = b"\x0e\x00"
    annotated: bool = True
    visibility: int = 1
    annotation_type: bytes = JUNIT


def _fixture(methods=(_Method(),), *, owner=OWNER, class_flags=1,
             define_class=True, code_shift=0, result=b"V", parameters=0):
    """Independent tiny layout. Metadata precedes aligned, final code items.

    Code at EOF is deliberate: later annotations cannot make truncated insns
    appear in bounds. No method/code is generated by the production decoder.
    Method references can exist without either a class or method definition.
    """
    assert 0 <= parameters <= 2
    methods = tuple(sorted(methods, key=lambda item: item.name))
    assert len({item.name for item in methods}) == len(methods) <= 4
    types = sorted({owner, b"V", b"I", result, JUNIT, OTHER_ANNOTATION})
    shorty = result + b"I" * parameters
    strings = sorted(set(types) | {shorty} | {item.name for item in methods})
    string_off = 112
    type_off = string_off + 4 * len(strings)
    proto_off = type_off + 4 * len(types)
    method_off = proto_off + 12
    class_off = method_off + 8 * len(methods)
    data = bytearray(class_off + (32 if define_class else 0))
    data[:8] = b"dex\n039\0"
    struct.pack_into("<II", data, 36, 112, 0x12345678)
    for header, count, offset in ((56, len(strings), string_off),
                                  (64, len(types), type_off),
                                  (72, 1, proto_off),
                                  (88, len(methods), method_off),
                                  (96, int(define_class), class_off if define_class else 0)):
        struct.pack_into("<II", data, header, count, offset)
    for index, value in enumerate(strings):
        struct.pack_into("<I", data, string_off + 4 * index, len(data))
        data.extend(_uleb(len(value)) + value + b"\0")
    for index, value in enumerate(types):
        struct.pack_into("<I", data, type_off + 4 * index, strings.index(value))
    param_off = 0
    if parameters:
        data.extend(bytes((-len(data)) % 4))
        param_off = len(data)
        data.extend(struct.pack("<I", parameters))
        data.extend(struct.pack("<" + "H" * parameters, *([types.index(b"I")] * parameters)))
    struct.pack_into("<III", data, proto_off, strings.index(shorty),
                     types.index(result), param_off)
    for index, item in enumerate(methods):
        struct.pack_into("<HHI", data, method_off + 8 * index,
                         types.index(owner), 0, strings.index(item.name))
    annotations = []
    definitions = [(index, item) for index, item in enumerate(methods)
                   if define_class and item.defined]
    for index, item in definitions:
        if not item.annotated:
            continue
        annotation = len(data)
        data.extend(bytes([item.visibility]) + _uleb(types.index(item.annotation_type)) + b"\0")
        data.extend(bytes((-len(data)) % 4))
        annotation_set = len(data)
        data.extend(struct.pack("<II", 1, annotation))
        annotations.append((index, annotation_set))
    directory = 0
    if annotations:
        data.extend(bytes((-len(data)) % 4))
        directory = len(data)
        data.extend(struct.pack("<IIII", 0, 0, len(annotations), 0))
        for pair in annotations:
            data.extend(struct.pack("<II", *pair))
    code_offsets = {index: 1024 + 128 * index + code_shift
                    for index, item in definitions if item.has_code}
    body = 0
    if definitions:
        body = len(data)
        direct = [(index, item) for index, item in definitions if item.flags & 8]
        virtual = [(index, item) for index, item in definitions if not item.flags & 8]
        data.extend(b"\0\0" + _uleb(len(direct)) + _uleb(len(virtual)))
        for group in (direct, virtual):
            previous = 0
            for index, item in group:
                data.extend(_uleb(index - previous) + _uleb(item.flags) +
                            _uleb(code_offsets.get(index, 0)))
                previous = index
    if define_class:
        struct.pack_into("<IIIIIIII", data, class_off, types.index(owner),
                         class_flags, 0xFFFFFFFF, 0, 0xFFFFFFFF, directory, body, 0)
    for index, item in definitions:
        if not item.has_code:
            continue
        offset = code_offsets[index]
        assert len(data) <= offset and len(item.instructions) <= 100
        data.extend(bytes(offset - len(data)))
        # registers/ins deliberately differ from the tested instruction count.
        data.extend(struct.pack("<HHHHII", 7, parameters + 1, 0, 0, 0,
                                item.declared_units))
        data.extend(item.instructions)
    struct.pack_into("<I", data, 32, len(data))
    return bytes(data)


def _resize(raw, size):
    result = bytearray(raw[:size])
    struct.pack_into("<I", result, 32, len(result))
    return bytes(result)


def _apk(entries):
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in entries:
            archive.writestr(name, data)
    stream.seek(0)
    return stream


class DiagnosticUiDexTests(unittest.TestCase):
    def test_legacy_default_and_explicit_false_preserve_exact_four_tuple(self):
        raw = _fixture()
        expected = {OWNER: (1, [(b"reviewCase", (b"V", 0), 1, True)])}
        self.assertEqual(expected, audit.Dex(raw).definitions())
        self.assertEqual(expected, audit.Dex(raw).definitions(with_code=False))
        self.assertEqual(4, len(audit.Dex(raw).definitions()[OWNER][1][0]))

    def test_opt_in_appends_actual_units_without_changing_prior_fields(self):
        raw = _fixture((_Method(b"first"), _Method(b"second", declared_units=3,
                                                   instructions=b"\x0e\0\0\0\0\0")))
        self.assertEqual({OWNER: (1, [
            (b"first", (b"V", 0), 1, True, 1),
            (b"second", (b"V", 0), 1, True, 3),
        ])}, audit.Dex(raw).definitions(with_code=True))
        old = audit.Dex(raw).definitions()
        new = audit.Dex(raw).definitions(with_code=True)
        self.assertEqual(old[OWNER][1], [item[:4] for item in new[OWNER][1]])

    def test_absent_and_empty_code_have_zero_units_but_keep_runtime_annotation(self):
        for item in (_Method(has_code=False),
                     _Method(declared_units=0, instructions=b"")):
            with self.subTest(item=item):
                self.assertEqual((b"reviewCase", (b"V", 0), 1, True, 0),
                                 audit.Dex(_fixture((item,))).definitions(with_code=True)[OWNER][1][0])

    def test_unit_count_comes_from_offset_twelve_and_exact_code_span_fits(self):
        raw = _fixture((_Method(declared_units=2, instructions=b"\x0e\0\0\0"),))
        self.assertEqual(2, audit.Dex(raw).definitions(with_code=True)[OWNER][1][0][4])
        self.assertEqual(1024 + 16 + 2 * 2, len(raw))

    def test_truncated_instruction_array_refuses_only_in_requested_mode(self):
        for claimed, payload in ((2, b"\x0e\0"), (1, b"\x0e"), (3, b"\0" * 5)):
            raw = _fixture((_Method(declared_units=claimed, instructions=payload),))
            with self.subTest(claimed=claimed, available=len(payload)):
                self.assertEqual(4, len(audit.Dex(raw).definitions()[OWNER][1][0]))
                self.assertEqual(audit.Dex(raw).definitions(),
                                 audit.Dex(raw).definitions(with_code=False))
                with self.assertRaises(audit.AuditError):
                    audit.Dex(raw).definitions(with_code=True)

    def test_huge_declared_count_is_range_checked_without_allocation(self):
        raw = _fixture((_Method(declared_units=0xFFFFFFFF),))
        self.assertEqual(4, len(audit.Dex(raw).definitions()[OWNER][1][0]))
        with self.assertRaises(audit.AuditError):
            audit.Dex(raw).definitions(with_code=True)

    def test_unaligned_code_offset_is_not_silently_rounded_or_accepted(self):
        for shift in (1, 2, 3):
            raw = _fixture(code_shift=shift)
            with self.subTest(shift=shift):
                self.assertEqual(4, len(audit.Dex(raw).definitions()[OWNER][1][0]))
                with self.assertRaises(audit.AuditError):
                    audit.Dex(raw).definitions(with_code=True)

    def test_short_code_header_still_refuses_in_both_modes(self):
        raw = _resize(_fixture(), 1024 + 15)
        for enabled in (False, True):
            with self.subTest(enabled=enabled), self.assertRaises(audit.AuditError):
                audit.Dex(raw).definitions(with_code=enabled)

    def test_with_code_requires_an_actual_bool_at_both_entry_points(self):
        raw = _fixture()
        for value in (None, 0, 1, 0.0, "true", [], object()):
            with self.subTest(value_type=type(value).__name__):
                with self.assertRaises(audit.AuditError):
                    audit.Dex(raw).definitions(with_code=value)
                with self.assertRaises(audit.AuditError):
                    audit.dex_classes(_apk((("classes.dex", raw),)), with_code=value)

    def test_apk_aggregator_forwards_mode_for_every_dex(self):
        second = b"Lsynthetic/SecondTest;"
        entries = (("classes.dex", _fixture()),
                   ("classes2.dex", _fixture(owner=second)))
        with _apk(entries) as stream:
            legacy = audit.dex_classes(stream)
        with _apk(entries) as stream:
            observed = audit.dex_classes(stream, with_code=True)
        self.assertEqual({OWNER, second}, set(observed))
        self.assertEqual(legacy, {key: (flags, [m[:4] for m in methods])
                                  for key, (flags, methods) in observed.items()})
        self.assertEqual([1, 1], [observed[key][1][0][4] for key in (OWNER, second)])
        bad = _fixture((_Method(declared_units=2),), owner=second)
        with _apk((("classes.dex", entries[0][1]), ("classes2.dex", bad))) as stream:
            with self.assertRaises(audit.AuditError):
                audit.dex_classes(stream, with_code=True)

    def test_native_abstract_and_static_role_facts_are_not_relabelled_as_runnable(self):
        for flags, has_code, units in ((0x101, False, 0), (0x401, False, 0), (9, True, 1)):
            raw = _fixture((_Method(flags=flags, has_code=has_code),))
            with self.subTest(flags=flags):
                self.assertEqual((b"reviewCase", (b"V", 0), flags, True, units),
                                 audit.Dex(raw).definitions(with_code=True)[OWNER][1][0])
        raw = _fixture(class_flags=0x401)
        self.assertEqual(0x401, audit.Dex(raw).definitions(with_code=True)[OWNER][0])

    def test_nonvoid_and_parameterized_signatures_remain_explicit_facts(self):
        for result, parameters in ((b"I", 0), (b"V", 1)):
            with self.subTest(result=result, parameters=parameters):
                member = audit.Dex(_fixture(result=result, parameters=parameters)).definitions(with_code=True)[OWNER][1][0]
                self.assertEqual((result, parameters), member[1])
                self.assertEqual(1, member[4])

    def test_references_and_annotation_roles_do_not_create_test_definitions(self):
        raw = _fixture(define_class=False)
        reader = audit.Dex(raw)
        self.assertTrue(any(owner == OWNER for owner, _, _ in reader.methods))
        self.assertEqual({}, reader.definitions(with_code=True))
        raw = _fixture((_Method(defined=False),))
        self.assertEqual((1, []), audit.Dex(raw).definitions(with_code=True)[OWNER])
        raw = _fixture((_Method(annotation_type=OTHER_ANNOTATION),))
        self.assertEqual((b"reviewCase", (b"V", 0), 1, False, 1),
                         audit.Dex(raw).definitions(with_code=True)[OWNER][1][0])
        for visibility in (0, 2):
            with self.subTest(visibility=visibility), self.assertRaises(audit.AuditError):
                audit.Dex(_fixture((_Method(visibility=visibility),))).definitions(with_code=True)

    def test_opt_in_retains_multidex_duplicate_class_and_version_refusals(self):
        raw = _fixture()
        with _apk((("classes.dex", raw), ("classes2.dex", raw))) as stream:
            with self.assertRaises(audit.AuditError):
                audit.dex_classes(stream, with_code=True)
        bad = bytearray(raw)
        bad[:8] = b"dex\n041\0"
        with self.assertRaises(audit.AuditError):
            audit.Dex(bytes(bad)).definitions(with_code=True)
